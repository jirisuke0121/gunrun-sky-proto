const assert = require('node:assert/strict');
(async () => {
  const { createPursuit, approachingPursuer } = await import('../guided-defense.js');
  const { createLessons } = await import('../guided-lessons.js');
  const { describeLesson } = await import('../guided-prompts.js');
  const c = {pos:{x:176,y:0,z:0},h:1.75,r:.32,state:'normal',onGround:true};
  const enemy = {pos:{x:169,y:0,z:0},vel:{x:3,y:0,z:0},r:.3,h:1.8};
  const sky = {c,raycast:()=>null,jn:[]}, targets = [enemy], origins = createPursuit(targets);
  assert.equal(approachingPursuer(sky,targets,origins),undefined,'a distant pursuer does not freeze the course');
  enemy.pos.x=172.5;
  assert.equal(approachingPursuer(sky,targets,origins),enemy,'a real approaching zombie triggers Flash within four metres');
  const fresh = createPursuit(targets);
  assert.equal(approachingPursuer(sky,targets,fresh),undefined,'spawning a zombie nearby is not pursuit');
  enemy.vel.x=-3;assert.equal(approachingPursuer(sky,targets,origins),undefined,'a zombie moving away is not pursuit');enemy.vel.x=3;
  enemy.stun=1;assert.equal(approachingPursuer(sky,targets,origins),undefined);enemy.stun=0;
  enemy.pos.y=4;assert.equal(approachingPursuer(sky,targets,origins),undefined);enemy.pos.y=0;
  assert.equal(approachingPursuer({...sky,raycast:()=>({t:1})},targets,origins),undefined,'a wall blocks the cue');
  global.window={skyPracticeCourse:{sections:[]},skyFlashbang:{stats:{affected:0},grenades:[]}};
  global.location={search:'?return=canyon'};
  const progress={stats:{},flash:0,flashPursued:false}, game={P:c,stats:{}}, practice={targets};
  const flow=createLessons(sky,game,practice,progress), lesson=flow.lessons.find(l=>l.id==='flash');
  assert.equal(flow.lessons.some(l=>l.id==='decoy'),false,'no second defensive-skill task');
  const cue=()=>describeLesson(lesson,{game,sky,practice,progress,goal:flow.goal,near:flow.near,english:false});
  assert.equal(cue().action,'','no Flash pause before pursuit');
  assert.equal(cue().motion,'toward','the player escapes before the pause');
  progress.flashPursued=true;
  assert.equal(cue().action,'tFlash');assert.ok(cue().press);
  window.skyFlashbang.grenades.push({});assert.equal(cue().action,'','throw is not repeated during the fuse');
  window.skyFlashbang.grenades.length=0;window.skyFlashbang.stats.affected=1;
  assert.equal(cue().cue,'escape');assert.equal(cue().action,'');assert.equal(cue().motion,'toward');
  assert.deepEqual(cue().at,[181,0,0]);assert.equal(lesson.done(),false,'stun alone is not escape');
  c.pos.x=181;assert.equal(lesson.done(),true,'stun then escape advances directly toward the barrel');
  c.onGround=false;assert.equal(lesson.done(),false);c.onGround=true;
  progress.flashPursued=false;assert.equal(lesson.done(),false,'an early throw does not replace a chase');
  console.log('PASS pursuit, distance, approach, stun, floor, wall, Flash cue, escape and no Decoy task');
})().catch(e=>{console.error(e);process.exitCode=1});
