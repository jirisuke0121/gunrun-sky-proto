// node tools/i18n/build_packs.cjs [--check]
// Builds i18n-en-extra.js (extra Japanese->English strings and patterns used by the guided scripts) and
// i18n-<lang>.js (es pt tr vi th) from tools/i18n/src/<lang>.*.txt.  Source lines are "<id> <text>" (exact string,
// ids from keys.tsv) or "p<index> <template>" (pattern; see i18n.js for the template syntax). "\n" means a line break.
const fs = require('fs'), path = require('path');
const { ROOT, LANGS, unesc, readTsv, loadBase, loadExtras, EXTRA_PATTERNS } = require('./lib.cjs');
const check = process.argv.includes('--check');
const errors = [];
const warn = msg => errors.push(msg);

const base = loadBase();
const extras = loadExtras();
const keyRows = readTsv(path.join(__dirname, 'keys.tsv'));
const idToJp = new Map(keyRows.filter(r => /^\d+$/.test(r[0])).map(r => [r[0], r[1]]));
const patternRows = keyRows.filter(r => /^p\d+$/.test(r[0]));
const allPatterns = [...base.patterns, ...EXTRA_PATTERNS];
const groups = src => new RegExp(src + '|').exec('').length - 1;

// i18n-en-extra.js
{
  const exact = Object.fromEntries(extras);
  const pats = EXTRA_PATTERNS.map(([src, rep]) => `[new RegExp(${JSON.stringify(src)}),${JSON.stringify(rep)}]`).join(',');
  const body = `// Extra Japanese->English strings for the guided scripts (generated by tools/i18n/build_packs.cjs from extra-src.tsv).\n` +
    `(()=>{const b=window.skyI18nEn;Object.assign(b.exact,${JSON.stringify(exact)});b.patterns.push(${pats});})();\n`;
  if (!check) fs.writeFileSync(path.join(ROOT, 'i18n-en-extra.js'), body);
}

const report = {};
for (const lang of LANGS) {
  const dir = path.join(__dirname, 'src');
  const files = fs.readdirSync(dir).filter(f => f.startsWith(lang + '.') && f.endsWith('.txt')).sort();
  const exact = {}, patterns = {};
  const seen = new Set();
  for (const file of files) {
    fs.readFileSync(path.join(dir, file), 'utf8').split('\n').forEach((line, i) => {
      if (!line.trim() || line.startsWith('#')) return;
      const m = /^(p?\d+) ?(.*)$/.exec(line);
      const where = `${file}:${i + 1}`;
      if (!m) return warn(`${where}: cannot parse`);
      const [, id, rawText] = m;
      if (seen.has(id)) return warn(`${where}: duplicate id ${id}`);
      seen.add(id);
      const text = unesc(rawText);
      if (id[0] === 'p') {
        const idx = +id.slice(1);
        if (!allPatterns[idx]) return warn(`${where}: unknown pattern ${id}`);
        const n = groups(allPatterns[idx][0]);
        for (const [, d] of text.matchAll(/\$(\d)/g)) if (+d > n) warn(`${where}: $${d} but the regex has ${n} groups`);
        for (const [, d] of text.matchAll(/\[(\d)[=?]/g)) if (+d > n) warn(`${where}: [${d}…] but the regex has ${n} groups`);
        patterns[idx] = text;
      } else {
        const jp = idToJp.get(id);
        if (jp === undefined) return warn(`${where}: unknown id ${id}`);
        if (!text.trim()) return warn(`${where}: empty translation for ${id}`);
        exact[jp] = text;
      }
    });
  }
  const missingExact = [...idToJp].filter(([id]) => !seen.has(id)).map(([id]) => id);
  const skippable = new Set([44, 46, 48, 69, 78, 84, 89, 94]); // numbers only / nested lookups only / unreachable
  const missingPatterns = allPatterns.map((_, i) => i).filter(i => !skippable.has(i) && !seen.has('p' + i));
  if (missingExact.length) warn(`${lang}: ${missingExact.length} ids without translation (${missingExact.slice(0, 12).join(',')}…)`);
  if (missingPatterns.length) warn(`${lang}: patterns without translation: ${missingPatterns.join(',')}`);
  report[lang] = { exact: Object.keys(exact).length, patterns: Object.keys(patterns).length };
  const out = `// ${lang} language pack: Japanese text -> ${lang}. Generated by tools/i18n/build_packs.cjs from tools/i18n/src/${lang}.*.txt; do not edit.\n` +
    `(window.skyI18nPacks=window.skyI18nPacks||{}).${lang}=${JSON.stringify({ exact, patterns })};\n`;
  if (!check) fs.writeFileSync(path.join(ROOT, `i18n-${lang}.js`), out);
}
console.log(JSON.stringify(report));
if (errors.length) { console.error(errors.join('\n')); process.exit(1); }
console.log(check ? 'check ok' : 'built');
